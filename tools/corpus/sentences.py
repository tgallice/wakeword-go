WAKE_WORD_PATTERNS = [re.compile(r"\b" + w + r"\b") for w in
                      ("alexa", "hey jarvis", "hey mycroft", "okay nabu")]


def check_negatives():
    """Return sentences that contain a whole wake word (Alexander is fine, Alexa is not)."""
    bad = []
    for s in NEGATIVES:
        low = s.lower()
        for pat in WAKE_WORD_PATTERNS:
            if pat.search(low):
                bad.append((s, pat.pattern))
    return bad


